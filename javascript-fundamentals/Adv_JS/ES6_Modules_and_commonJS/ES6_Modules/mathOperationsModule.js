// Keep the things you want to export

// There is no major differece between 'export function' and 'export default function'. You will notice a small difference when you will import those.

export function add(a, b)
{
    return a + b;
}

export function subtract(a, b)
{
    return a - b;
}

export default function multiply(a, b)
{
    return a * b;
}

